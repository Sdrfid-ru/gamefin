    private fun introduction(id: Int): String =
        when (id) {
            0 ->
                "“Нужно” — это то, без чего трудно обойтись: еда, вода, уход и другие важные вещи. “Хочу” — то, что радует, но покупку можно отложить. Если сомневаешься, спроси себя: “Что будет, если я не куплю это сегодня?”"
            1 ->
                "Сначала подумай о важном, потом — о желаниях, а часть монет постарайся сохранить для своей цели. Например, из 100 монет можно 50 оставить на “Нужно”, 20 — на “Хочу”, а 30 — отложить. Но это только пример — свой план выбираешь ты!"
            2 ->
                "Копить — значит откладывать часть монет сейчас, чтобы позже купить что-то важное. Подумай: сколько можно отложить, чтобы и на нужное осталось?"
            3 ->
                "Большая мечта становится ближе, если копить понемногу, но регулярно. Лучше сначала запланировать накопление, а уже потом решать, что делать с оставшимися монетами."
            4 ->
                "Выгодно — не всегда значит просто “дешевле”. Посчитай, сколько стоит одна вещь в каждом варианте, и подумай, действительно ли тебе нужно такое количество."
            5 ->
                "Сначала — важное, потом — желаемое. Следи за суммой покупок: она не должна быть больше твоего бюджета."
            else -> error("Unknown task")
        }

